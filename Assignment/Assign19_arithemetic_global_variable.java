package Assignments_1to100;
//WAP on different arithmetic operators using global variable a and b
public class Assign19_arithemetic_global_variable
{
	static int num=11;
	static int num2=12;
	
	public static void main(String[] args) 
	{
		
		int sum=num+num2;
		System.out.println(sum);
		
		int sub=num-num2;
		System.out.println(sub);
		
		int mul=num*num2;
		System.out.println(mul);
		
		double div=num/num2;
		System.out.println(div);
		
		double modulus=num%num2;
		System.out.println(modulus);


	}

}
