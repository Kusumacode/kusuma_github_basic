package Assignments_1to100;
//If Else If program with 4 else if block
public class Assign11_4elseIfblock 
{
	public static void main(String[] args) 
	{
		int a=100;
		int b=200;
		
		if(a>b)
		{
			System.out.println("the condition is false");
		}
		else if(b<a)
		{
			System.out.println("the condition is b is greater than a");
		}
		else if(a<b)
		{
			System.out.println("the condition is a is less than b");
		}
		else if(a!=b) 
		{
			System.out.println("the condition is true");
		}
		else
		{
			System.out.println("the condition is false");
		}

	}

}
